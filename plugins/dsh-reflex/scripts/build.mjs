import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = new URL('../', import.meta.url);
const source = await readFile(new URL('../../webview-host/ChatModes.cs', root), 'utf8');
const modes = [...source.matchAll(/new ChatModeDefinition\("([^"\\]+)","([^"\\]+)","([^"\\]*)"\)/g)].map(([, id, name, instruction]) => ({ id, name, instruction }));
if (modes.length !== 6 || new Set(modes.map(m => m.id)).size !== modes.length) throw new Error('Review changed C# mode catalog before building the plugin');
const themeSource = await readFile(new URL('../../webview-host/SettingsPanelControls.cs', root), 'utf8');
const names = name => name.replace(/[A-Z]/g, (letter, index) => (index ? '-' : '') + letter.toLowerCase());
function metric(name, factor = 1, unit = 'px') {
  const match = themeSource.match(new RegExp('\\b' + name + '=(\\d+(?:\\.\\d+)?)f?\\b'));
  if (!match) throw new Error('Missing shared UI metric: ' + name);
  return ['--reflex-' + names(name), (Number(match[1]) * factor) + unit];
}
const colors = ['Ink','Muted','Accent','Tint','Border','Surface','Hover','Pressed','AccentHover','AccentPressed','InputBorder','CloseHover','ClosePressed'];
const variables = colors.map(name => {
  const match = themeSource.match(new RegExp('\\b' + name + '=Color\\.FromArgb\\((\\d+),(\\d+),(\\d+)\\)'));
  if (!match || match.slice(1).some(value => Number(value) > 255)) throw new Error('Missing shared UI color: ' + name);
  return ['--reflex-' + names(name), '#' + match.slice(1).map(value => Number(value).toString(16).padStart(2, '0')).join('')];
});
variables.push(...['CaptionSize','BodySize','TitleSize','HeadingSize'].map(name => metric(name, 4 / 3)));
variables.push(...['ControlRadius','PanelRadius','ControlHeight','InputHeight'].map(name => metric(name)));
variables.push(...['HoverDuration','PressDuration','ReleaseDuration'].map(name => metric(name, 1, 'ms')));
const family = themeSource.match(/FontFamily="([^"\\]+)"/);
if (!family) throw new Error('Missing shared UI font family');
const theme = { fontFamily: family[1], variables: Object.fromEntries(variables) };
const output = await build({ absWorkingDir: fileURLToPath(root), entryPoints: [fileURLToPath(new URL('src/client.js', root))], bundle: true, write: false, format: 'iife', globalName: 'ReflexClient', target: 'es2022', external: ['react'], define: { __REFLEX_MODES__: JSON.stringify(modes), __REFLEX_THEME__: JSON.stringify(theme) }, banner: { js: "// Generated by npm run build. Modes and UI tokens originate in webview-host.\nwindow.__ModuleLoader__.load({ id: '@deepseek-reflex/dsh-plugin', factory(require) {" }, footer: { js: 'return ReflexClient.plugin;\n} });' } });
if (process.argv.includes('--check')) {
  if (await readFile(new URL('client.js', root), 'utf8') !== output.outputFiles[0].text) throw new Error('client.js is stale; run npm run build');
  console.log('PASS browser artifact matches source, six shared modes and native UI tokens');
} else {
  await writeFile(new URL('client.js', root), output.outputFiles[0].text);
  console.log('Built client.js with shared Reflex modes and native UI tokens');
}
