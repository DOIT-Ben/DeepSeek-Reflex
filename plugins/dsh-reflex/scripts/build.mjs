import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = new URL('../', import.meta.url);
const source = await readFile(new URL('../../webview-host/ChatModes.cs', root), 'utf8');
const modes = [...source.matchAll(/new ChatModeDefinition\("([^"\\]+)","([^"\\]+)","([^"\\]*)"\)/g)].map(([, id, name, instruction]) => ({ id, name, instruction }));
if (modes.length !== 6 || new Set(modes.map(m => m.id)).size !== modes.length) throw new Error('Review changed C# mode catalog before building the plugin');
const output = await build({ absWorkingDir: fileURLToPath(root), entryPoints: [fileURLToPath(new URL('src/client.js', root))], bundle: true, write: false, format: 'iife', globalName: 'ReflexClient', target: 'es2022', external: ['react'], define: { __REFLEX_MODES__: JSON.stringify(modes) }, banner: { js: "// Generated by npm run build. Mode definitions originate in webview-host/ChatModes.cs.\nwindow.__ModuleLoader__.load({ id: '@deepseek-reflex/dsh-plugin', factory(require) {" }, footer: { js: 'return ReflexClient.plugin;\n} });' } });
if (process.argv.includes('--check')) {
  if (await readFile(new URL('client.js', root), 'utf8') !== output.outputFiles[0].text) throw new Error('client.js is stale; run npm run build');
  console.log('PASS browser artifact matches source and six shared modes');
} else {
  await writeFile(new URL('client.js', root), output.outputFiles[0].text);
  console.log('Built client.js with six shared Reflex modes');
}
